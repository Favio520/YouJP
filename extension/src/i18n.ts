export function uiText(language: UiLanguage, spanish: string, english?: string): string {
  if (language !== 'en') return spanish;
  const retry = /^Intento (\d+) en ([\d.]+) s\. Puedes detener la captura con el icono\.$/.exec(spanish);
  if (retry) return `Attempt ${retry[1]} in ${retry[2]} s. Use the icon to stop capture.`;
  if (spanish.startsWith('Dirección del backend no válida: ')) return spanish.replace('Dirección del backend no válida: ', 'Invalid backend address: ');
  const identity = /^El backend no reconoce esta extensión \(ID (.+)\)\./.exec(spanish);
  if (identity) return `The backend does not recognize this extension (ID ${identity[1]}). Load the built YouJP extension or add this ID to YOUJP_ALLOWED_EXTENSION_IDS.`;
  if (/^Error del servidor \(\d+\)$/.test(spanish)) return spanish.replace('Error del servidor', 'Server error');
  return english ?? ENGLISH[spanish] ?? spanish.split(' · ').map((part) => ENGLISH[part] ?? part).join(' · ');
}
